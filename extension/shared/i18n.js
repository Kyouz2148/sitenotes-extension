/**
 * Resolves the active language ('en' or 'pt') from user preference and browser locale.
 * @param {'auto' | 'en' | 'pt'} preference
 * @returns {'en' | 'pt'}
 */
export function resolveLanguage(preference = 'auto') {
  if (preference === 'pt' || preference === 'en') {
    return preference;
  }
  let browserLang = 'en';
  try {
    if (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage) {
      browserLang = chrome.i18n.getUILanguage();
    } else if (typeof navigator !== 'undefined' && navigator.language) {
      browserLang = navigator.language;
    }
  } catch {
    browserLang = 'en';
  }
  return browserLang.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

/**
 * Translates a key with optional template variables.
 * @param {'en' | 'pt'} lang
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 * @returns {string}
 */
export function t(lang, key, vars = {}) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let template = dict[key] ?? TRANSLATIONS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    template = template.replaceAll(`{${k}}`, String(v));
  }
  return template;
}
